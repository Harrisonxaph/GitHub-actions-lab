"""Four basic arithmetic operations for the CI learning project."""


def add(a, b):
    """Return the sum of two numbers."""
    return a + b


def subtract(a, b):
    """Subtract b from a."""
    return a - b


def multiply(a, b):
    """Return the product of two numbers."""
    return a * b


def divide(a, b):
    """Divide a by b; raise ZeroDivisionError when b is zero."""
    return a / b
